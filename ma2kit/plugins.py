"""Install, update, run and remove this repo's Lua plugins in the loaded show.

Verified on onPC 3.9.61:
  * `Import "ma2kit/x.xml" At Plugin N` resolves the path inside the plugins folder ($PLUGINPATH) and
    replies `1 object(s) from "x.xml" imported.`; the XML's `luafile` is relative to the XML file.
  * The show stores the plugin code at import time: `ReloadPlugins /nc` restarts the Lua engine but
    does NOT re-read edited files. Updating means importing again over the same slot.
  * `Plugin "name"` starts a plugin and returns to the prompt at once; gma.feedback() text arrives later.
  * `Delete Plugin N /nc` removes the pool entry (files on disk stay; this module deletes ours).
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from .client import MA2Error
from .config import REPO_ROOT
from .model import ShowModel

SOURCE_DIR = REPO_ROOT / "lua" / "plugins"
LIB_FILE = REPO_ROOT / "lua" / "lib" / "ma2kit.lua"
INSTALL_SUBDIR = "ma2kit"  # subfolder of the console's plugins folder that holds our files
NAME_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]{0,30}$")
DESC_RE = re.compile(r"^--\s*description:\s*(.+)$", re.MULTILINE)
IMPORTED_RE = re.compile(r"(\d+) object\(s\) from .* imported")
DONE_PREFIX = "MA2KIT_DONE"

XML_TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<MA xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns="http://schemas.malighting.de/grandma2/xml/MA" xsi:schemaLocation="http://schemas.malighting.de/grandma2/xml/MA http://schemas.malighting.de/grandma2/xml/3.9.61/MA.xsd" major_vers="3" minor_vers="9" stream_vers="61">
\t<Info datetime="2026-01-01T00:00:00" showfile="ma2kit" />
\t<Plugin index="0" execute_on_load="0" name="{name}" luafile="{name}.lua" />
</MA>
"""

BUNDLE_TEMPLATE = """-- Generated by ma2kit from lua/plugins/{name}.lua. Edit the source in the repo, not this file.
-- Line numbers in errors: subtract {offset} to get the line in the source file.
{lib}
local __ma2kit_start, __ma2kit_cleanup = (function(...)
{body}
end)(...)
if type(__ma2kit_start) ~= "function" then
    error("{name}: the plugin must end with 'return Start'")
end
return function(...) return ma2kit._run("{name}", __ma2kit_start, ...) end, __ma2kit_cleanup
"""


@dataclass
class SourcePlugin:
    name: str
    path: Path
    description: str


@dataclass
class PluginStatus:
    name: str
    description: str
    slot: int | None  # plugin pool number in the loaded show, None = not installed
    files_installed: bool


def source_plugins(directory: Path = SOURCE_DIR) -> list[SourcePlugin]:
    out = []
    for path in sorted(directory.glob("*.lua")):
        if not NAME_RE.match(path.stem):
            continue
        match = DESC_RE.search(path.read_text(encoding="utf-8"))
        out.append(SourcePlugin(path.stem, path, match.group(1).strip() if match else ""))
    return out


def get_source(name: str, directory: Path = SOURCE_DIR) -> SourcePlugin:
    for plugin in source_plugins(directory):
        if plugin.name == name:
            return plugin
    raise MA2Error(f"no plugin source lua/plugins/{name}.lua")


def body_offset(lib_text: str) -> int:
    """Lines in the installed file before the plugin's own first line."""
    lib = lib_text.rstrip("\n")
    return 2 + (lib.count("\n") + 1) + 1  # 2 header lines + library + the "(function" line


def bundle(plugin: SourcePlugin, lib_text: str) -> str:
    return BUNDLE_TEMPLATE.format(
        name=plugin.name,
        lib=lib_text.rstrip("\n"),
        body=plugin.path.read_text(encoding="utf-8").rstrip("\n"),
        offset=body_offset(lib_text),
    )


# Verified: errors read like [string "plugin_101_ma2kit_selftest_error"]:100: deliberate test error
_CHUNK_LINE_RE = re.compile(r'\[string "plugin_\d+_([A-Za-z0-9_]+)"\]:(\d+):')


def map_error_lines(text: str, lib_text: str) -> str:
    """Rewrite installed-file line numbers in Lua errors to lua/plugins/<name>.lua:<line>."""
    offset = body_offset(lib_text)

    def repl(m: re.Match[str]) -> str:
        line = int(m.group(2)) - offset
        if line < 1:
            return f"lua/lib/ma2kit.lua:{int(m.group(2)) - 2}:"
        return f"lua/plugins/{m.group(1)}.lua:{line}:"

    return _CHUNK_LINE_RE.sub(repl, text)


def plugin_xml(name: str) -> str:
    return XML_TEMPLATE.format(name=name)


class PluginManager:
    def __init__(self, model: ShowModel, plugin_start: int = 100, source_dir: Path = SOURCE_DIR, lib_file: Path = LIB_FILE):
        self.model = model
        self.client = model.client
        self.plugin_start = plugin_start
        self.source_dir = source_dir
        self.lib_file = lib_file

    # -- state -----------------------------------------------------------
    def install_dir(self) -> Path:
        path = self.model.var("PLUGINPATH")
        if not path:
            raise MA2Error("could not read $PLUGINPATH from the console")
        return Path(path) / INSTALL_SUBDIR

    def pool_slots(self) -> dict[str, int]:
        """Plugin name -> pool number for everything in the loaded show's plugin pool."""
        return {item.name: n for item in self.model.pool("Plugin") if (n := item.number) is not None}

    def status(self) -> list[PluginStatus]:
        slots = self.pool_slots()
        target = self.install_dir()
        return [
            PluginStatus(p.name, p.description, slots.get(p.name), (target / f"{p.name}.lua").is_file())
            for p in source_plugins(self.source_dir)
        ]

    # -- actions ---------------------------------------------------------
    def write_files(self, name: str) -> Path:
        plugin = get_source(name, self.source_dir)
        target = self.install_dir()
        target.mkdir(parents=True, exist_ok=True)
        lua = bundle(plugin, self.lib_file.read_text(encoding="utf-8"))
        (target / f"{name}.lua").write_text(lua, encoding="utf-8", newline="\n")
        (target / f"{name}.xml").write_text(plugin_xml(name), encoding="utf-8", newline="\n")
        return target

    def free_slot(self) -> int:
        used = self.model.used_numbers("Plugin")
        n = self.plugin_start
        while n in used:
            n += 1
        return n

    def install(self, name: str, slot: int | None = None) -> int:
        slots = self.pool_slots()
        if name in slots:
            raise MA2Error(f"{name} is already installed as Plugin {slots[name]}; use update")
        if slot is None:
            slot = self.free_slot()
        elif slot in self.model.used_numbers("Plugin"):
            raise MA2Error(f"Plugin {slot} is already used")
        self.write_files(name)
        result = self.client.send(f'Import "{INSTALL_SUBDIR}/{name}.xml" At Plugin {slot}', timeout=20)
        if not result.ok or not IMPORTED_RE.search(result.text):
            raise MA2Error(f"import failed: {'; '.join(result.errors) or result.text.strip()}")
        if self.pool_slots().get(name) != slot:
            raise MA2Error(f"{name} not found at Plugin {slot} after import")
        return slot

    def update(self, names: list[str] | None = None) -> list[str]:
        """Rewrite the files of installed plugins and import them again over their own slot.

        Verified on 3.9.61: the show keeps its own copy of a plugin's code from the import, so
        `ReloadPlugins` does NOT pick up edited files. Importing again over the same slot does; the
        console asks "Overwrite Confirmation", which is answered "Overwrite" for this one object.
        """
        slots = self.pool_slots()
        names = names or [p.name for p in source_plugins(self.source_dir) if p.name in slots]
        missing = [n for n in names if n not in slots]
        if missing:
            raise MA2Error(f"not installed (use install): {', '.join(missing)}")
        for name in names:
            self.write_files(name)
            result = self.client.send(
                f'Import "{INSTALL_SUBDIR}/{name}.xml" At Plugin {slots[name]}',
                timeout=20,
                confirm=lambda dialog: dialog.option("Overwrite"),
            )
            if not result.ok or not IMPORTED_RE.search(result.text):
                raise MA2Error(f"re-import of {name} failed: {'; '.join(result.errors) or result.text.strip()}")
        return names

    def remove(self, name: str) -> int | None:
        slot = self.pool_slots().get(name)
        if slot is not None:
            result = self.client.send(f"Delete Plugin {slot} /nc")
            if not result.ok:
                raise MA2Error(f"Delete Plugin {slot} failed: {'; '.join(result.errors)}")
        target = self.install_dir()
        for suffix in (".lua", ".xml"):
            (target / f"{name}{suffix}").unlink(missing_ok=True)
        if target.is_dir() and not any(target.iterdir()):
            target.rmdir()
        return slot

    def run(self, name_or_slot: str, wait: float = 30.0) -> tuple[bool | None, str]:
        """Start a plugin. For ma2kit plugins wait for the completion marker.

        Returns (ok, output): ok is None when not waiting (non-ma2kit plugin or wait=0).
        """
        ref = name_or_slot if name_or_slot.isdigit() else f'"{name_or_slot}"'
        result = self.client.send(f"Plugin {ref}", timeout=20)
        if not result.ok:
            raise MA2Error(f"Plugin {ref} failed: {'; '.join(result.errors)}")
        name = name_or_slot
        if name_or_slot.isdigit():
            name = next((n for n, s in self.pool_slots().items() if str(s) == name_or_slot), name_or_slot)
        if wait <= 0 or not any(p.name == name for p in source_plugins(self.source_dir)):
            return None, result.late
        marker = re.compile(rf"{DONE_PREFIX} {re.escape(name)} (ok|error: [^\n]*)")
        output = self.client.wait_for(marker, timeout=wait)
        match = marker.search(output)
        lines = output[: match.start()].strip()
        status = match.group(1)
        if status != "ok":
            lines = (lines + "\n" if lines else "") + map_error_lines(status, self.lib_file.read_text(encoding="utf-8"))
        return status == "ok", lines
